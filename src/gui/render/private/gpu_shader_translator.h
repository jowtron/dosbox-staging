#ifndef DOSBOX_GPU_SHADER_TRANSLATOR_H
#define DOSBOX_GPU_SHADER_TRANSLATOR_H

#include <cstdint>
#include <optional>
#include <string>
#include <unordered_map>
#include <vector>

// Translates our OpenGL GLSL shaders (vertex and fragment stages in a single
// source, selected by the VERTEX and FRAGMENT defines) into a form the SDL_GPU
// API accepts: SPIR-V (Vulkan) or Metal Shading Language.
//
// The shaders are compiled with glslang under the "relaxed" Vulkan rules,
// which gather the loose `uniform` declarations into a single uniform block,
// then the SPIR-V is reflected and rebound with SPIRV-Cross to follow SDL_GPU's
// resource binding conventions. The MSL output is generated by SPIRV-Cross.
//
// Two adaptations keep the results identical to the OpenGL backend:
//
//  - The clip space Y axis is flipped in the vertex stage. Combined with
//    SDL_GPU's top-left texture origin, every render target ends up with the
//    same memory layout as in OpenGL (bottom row first), so texture
//    coordinates and `gl_FragCoord` behave exactly as in OpenGL.
//
//  - Fragment stage inputs get the locations of the vertex stage outputs of
//    the same name (OpenGL matches them by name, SPIR-V by location).
//
namespace GpuShaderTranslator {

enum class TargetFormat { Spirv, Msl };

struct UniformMember {
	int offset_bytes   = 0;
	int num_components = 0;
	bool is_int        = false;
};

struct StageShader {
	// MSL source text or SPIR-V binary
	std::vector<uint8_t> code = {};

	std::string entry_point = {};

	// Sampler slot N samples the pass input `sampler_inputs[N]` (i.e., the
	// texture bound to `INPUT_TEXTURE_<sampler_inputs[N]>`)
	std::vector<int> sampler_inputs = {};

	// Size of the uniform block in bytes (0 if the stage has no uniforms)
	int uniform_block_size_bytes = 0;

	std::unordered_map<std::string, UniformMember> uniforms = {};
};

struct TranslatedShader {
	StageShader vertex   = {};
	StageShader fragment = {};
};

struct Result {
	std::optional<TranslatedShader> shader = {};

	// Errors and warnings from the compilers
	std::string log = {};
};

Result Translate(const std::string& glsl_source, const TargetFormat format);

} // namespace GpuShaderTranslator

#endif // DOSBOX_GPU_SHADER_TRANSLATOR_H
